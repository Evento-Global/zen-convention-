/**
 * Scans repo-root /photos folders and emits src/data/photoManifest.generated.ts
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PHOTOS_DIR = path.join(ROOT, 'photos');
const OUT_FILE = path.join(ROOT, 'src', 'data', 'photoManifest.generated.ts');

/** Normalized folder label (trimmed) → option slug */
const FOLDER_TO_OPTION = {
  'Haldi traditional': 'haldi-traditional',
  'Haldi semi traditional - contemporary': 'haldi-semi-traditional-contemporary',
  'Pellikoduku- Pellikutru - traditional': 'pellikuturu-traditional',
  'Traditional mehendi': 'mehendi-traditional',
  'Semi traditional - contemporary mehendi': 'mehendi-semi-traditional-contemporary',
  'Sangeet led screen': 'sangeet-led',
  'Sangeet structural backdrop': 'sangeet-structure',
  'Wedding traditional': 'wedding-traditional',
  'Wedding semi traditional - contemporary': 'wedding-semi-traditional',
  'Cradle and birthday': 'cradle-birthday-contemporary',
  'Reception - engagement': 'reception-contemporary',
};

/** First gallery image used as home card hero per section id */
const COVER_FROM_OPTION = {
  haldi: 'haldi-traditional',
  pellikuturu: 'pellikuturu-traditional',
  mehendi: 'mehendi-traditional',
  sangeet: 'sangeet-led',
  wedding: 'wedding-traditional',
  reception: 'reception-contemporary',
  'cradle-birthday': 'cradle-birthday-contemporary',
};

const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i;

function encodePathSegment(seg) {
  return encodeURIComponent(seg).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
}

function toUrl(absoluteFilePath) {
  const rel = path.relative(PHOTOS_DIR, absoluteFilePath);
  const segments = rel.split(path.sep).map((s) => encodePathSegment(s));
  return `/photos/${segments.join('/')}`;
}

function resolveOptionId(dirName) {
  const trimmed = dirName.trim();
  if (FOLDER_TO_OPTION[dirName]) return FOLDER_TO_OPTION[dirName];
  if (FOLDER_TO_OPTION[trimmed]) return FOLDER_TO_OPTION[trimmed];
  for (const [k, v] of Object.entries(FOLDER_TO_OPTION)) {
    if (k.trim() === trimmed) return v;
  }
  return null;
}

function sortNatural(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

async function main() {
  const entries = await fs.readdir(PHOTOS_DIR, { withFileTypes: true }).catch(() => null);
  if (!entries) {
    const header = `// AUTO-GENERATED — photos folder missing. Run with /photos present.\nexport const OPTION_GALLERY_URLS = {} as const;\nexport const SECTION_COVER_URL = {} as const;\n`;
    await fs.writeFile(OUT_FILE, header, 'utf8');
    console.warn('[photos] Missing photos/ — wrote empty manifest.');
    return;
  }

  /** @type {Record<string, string[]>} */
  const byOption = {};

  for (const ent of entries) {
    if (!ent.isDirectory()) continue;
    const optionId = resolveOptionId(ent.name);
    if (!optionId) {
      console.warn(`[photos] Skip unmapped folder: ${JSON.stringify(ent.name)}`);
      continue;
    }
    const dirAbs = path.join(PHOTOS_DIR, ent.name);
    const files = await fs.readdir(dirAbs, { withFileTypes: true });
    const urls = files
      .filter((f) => f.isFile() && IMAGE_EXT.test(f.name))
      .map((f) => toUrl(path.join(dirAbs, f.name)))
      .sort(sortNatural);

    if (urls.length === 0) {
      console.warn(`[photos] No images in ${JSON.stringify(ent.name)}`);
      continue;
    }
    byOption[optionId] = urls;
  }

  /** @type {Record<string, string>} */
  const covers = {};
  for (const [sectionId, optionKey] of Object.entries(COVER_FROM_OPTION)) {
    const urls = byOption[optionKey];
    if (urls?.[0]) covers[sectionId] = urls[0];
  }

  const lines = [];
  lines.push('/** AUTO-GENERATED by `scripts/generate-photo-manifest.mjs` — do not edit. */');
  lines.push('');
  lines.push('export const OPTION_GALLERY_URLS = {');
  for (const key of Object.keys(byOption).sort(sortNatural)) {
    const arr = byOption[key];
    const body = arr.map((u) => `    ${JSON.stringify(u)},`).join('\n');
    lines.push(`  ${JSON.stringify(key)}: [\n${body}\n  ],`);
  }
  lines.push('} as const satisfies Record<string, readonly string[]>;');
  lines.push('');
  lines.push('export const SECTION_COVER_URL = {');
  for (const [k, v] of Object.entries(covers).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  }
  lines.push('} as const satisfies Record<string, string>;');
  lines.push('');

  await fs.writeFile(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`[photos] Wrote ${OUT_FILE} (${Object.keys(byOption).length} options, ${Object.keys(covers).length} covers).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
